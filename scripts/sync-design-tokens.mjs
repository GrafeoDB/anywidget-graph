/* global process, console */
// Writes the shared anywidgets look from the design tokens into this widget:
//   src/anywidget_graph/ui/styles.css  the colour, type and shape variables, between the
//                                      design-tokens:start and design-tokens:end markers
//   src/anywidget_graph/ui/palette.ts  the data colours (8 slots), Other, the background and the edge colour
// Usage: npm run sync-tokens -- <path/to/anywidgets/tokens.json>
// The variable names are the widget's public styling surface: they stay, only their values come from the tokens.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
if (!source) {
  console.error("usage: npm run sync-tokens -- <path/to/anywidgets/tokens.json>");
  process.exit(2);
}
const ui = path.join(here, "..", "src", "anywidget_graph", "ui");
const PREFIX = "awg";

// Widget variable -> design token. A function computes a value from the theme's tokens.
const MAP = {
  bg: "background",
  "bg-secondary": "surface",
  "bg-tertiary": "muted",
  border: "border",
  "border-strong": "border-strong",
  text: "foreground",
  "text-secondary": "muted-foreground",
  "text-muted": "muted-foreground",
  accent: "primary",
  "accent-hover": (t) => `color-mix(in srgb, ${t.primary} 80%, ${t.background})`,
  "on-accent": "primary-foreground",
  "graph-bg": "background",
  "input-bg": "background",
  "input-border": "border",
  selected: "selected",
  ring: "ring",
  edge: "edge",
  other: "input",
  ok: "status-ok",
  warn: "status-warn",
  error: "status-error",
  "font-body": "font-body",
  "font-mono": "font-mono",
  "radius-box": "radius-box",
  "radius-control": "radius-control",
  "shadow-float": "shadow-float",
};

const tokens = JSON.parse(readFileSync(source, "utf8"));

function block(selector, mode) {
  const t = tokens[mode];
  const lines = Object.entries(MAP).map(([name, token]) => {
    if (typeof token === "function") return `  --${PREFIX}-${name}: ${token(t)};`;
    if (!(token in t)) throw new Error(`design token "${token}" missing in ${mode}`);
    return `  --${PREFIX}-${name}: ${t[token]};`;
  });
  return `${selector} {\n${lines.join("\n")}\n}`;
}

const generated = `/* design-tokens:start (generated by scripts/sync-design-tokens.mjs from the anywidgets design tokens; do not edit) */
${block(`.${PREFIX}-wrapper`, "light")}

${block(`.${PREFIX}-wrapper.${PREFIX}-dark`, "dark")}
/* design-tokens:end */`;

const cssPath = path.join(ui, "styles.css");
const css = readFileSync(cssPath, "utf8");
if (!css.includes("design-tokens:start")) throw new Error("design-tokens markers not found in styles.css");
writeFileSync(cssPath, css.replace(/\/\* design-tokens:start[\s\S]*?\/\* design-tokens:end \*\//, generated));

function palette(mode) {
  const t = tokens[mode];
  const data = [1, 2, 3, 4, 5, 6, 7, 8].map((n) => JSON.stringify(t[`data-${n}`]));
  return `{\n  data: [${data.join(", ")}],\n  other: ${JSON.stringify(t.input)},\n  background: ${JSON.stringify(t.background)},\n  edge: ${JSON.stringify(t.edge)},\n}`;
}
writeFileSync(
  path.join(ui, "palette.ts"),
  `// Generated by scripts/sync-design-tokens.mjs from the anywidgets design tokens; do not edit.
// The data colours (8 slots in fixed order), Other, the background and the edge colour of each theme.
import type { Palette } from "./registry.ts";

export const LIGHT: Palette = ${palette("light")};

export const DARK: Palette = ${palette("dark")};
`,
);
console.log("styles.css and palette.ts written");
